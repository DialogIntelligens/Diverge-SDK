#!/usr/bin/env bash
# Sync VERSION into iOS, docs, README, and sample marketing version.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VERSION="$(tr -d '[:space:]' < "$ROOT/VERSION")"

if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+([.-].+)?$ ]]; then
  echo "Invalid VERSION: '$VERSION'" >&2
  exit 1
fi

replace_in_file() {
  local file="$1"
  local expression="$2"
  if [[ ! -f "$file" ]]; then
    echo "Skip missing file: $file" >&2
    return 0
  fi
  sed -i.bak -E "$expression" "$file"
  rm -f "${file}.bak"
}

# iOS — generated Version.swift
cat > "$ROOT/Sources/DivergeSDK/Version.swift" <<EOF
// Generated by scripts/sync-version.sh from VERSION. Do not edit by hand.
enum VersionInfo {
    static let current = "$VERSION"
}
EOF

# Docs site badge + getting started install snippets
replace_in_file "$ROOT/Docs/site/index.html" \
  "s/(docs scaffold · v)[0-9]+\\.[0-9]+\\.[0-9]+([.-][^<\"]*)?/\\1${VERSION}/"

replace_in_file "$ROOT/Docs/site/getting-started.html" \
  "s|(from: \")[0-9]+\\.[0-9]+\\.[0-9]+([.-][^\"]*)?(\")|\\1${VERSION}\\3|"
replace_in_file "$ROOT/Docs/site/getting-started.html" \
  "s|(ai\\.askdiverge:diverge-sdk:)[0-9]+\\.[0-9]+\\.[0-9]+([.-][^\"[:space:]<]*)?|\\1${VERSION}|"

# README install examples
replace_in_file "$ROOT/README.md" \
  "s|(from: \")[0-9]+\\.[0-9]+\\.[0-9]+([.-][^\"]*)?(\")|\\1${VERSION}\\3|"
replace_in_file "$ROOT/README.md" \
  "s|(ai\\.askdiverge:diverge-sdk:)[0-9]+\\.[0-9]+\\.[0-9]+([.-][^\"[:space:]]*)?|\\1${VERSION}|"

# iOS sample marketing version
PBX="$ROOT/Samples/iOS/DivergeSample.xcodeproj/project.pbxproj"
if [[ -f "$PBX" ]]; then
  replace_in_file "$PBX" "s/MARKETING_VERSION = [^;]+;/MARKETING_VERSION = ${VERSION};/"
fi

# XcodeGen project.yml (kept for optional regeneration)
YG="$ROOT/Samples/iOS/project.yml"
if [[ -f "$YG" ]]; then
  replace_in_file "$YG" "s/(MARKETING_VERSION: \")[0-9]+\\.[0-9]+\\.[0-9]+([.-][^\"]*)?(\")/\\1${VERSION}\\3/"
fi

echo "Synced version $VERSION"
